
-- Retail Sales Data Pipeline
-- Snowpipe for automatic customer CSV ingestion

CREATE OR REPLACE PIPE RETAIL_SALES_DB.RAW.CUSTOMERS_PIPE
    AUTO_INGEST = TRUE
AS
COPY INTO RETAIL_SALES_DB.RAW.CUSTOMERS
FROM @RETAIL_SALES_DB.RAW.RETAIL_S3_STAGE/customers/
FILE_FORMAT = 'RETAIL_SALES_DB.RAW.CSV_FORMAT';
